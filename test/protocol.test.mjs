import test from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { mkdtemp, mkdir, writeFile, appendFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';

test('stdio handshake, global discovery, resource and isolated inventory result', { timeout: 15000 }, async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'manager-protocol-'));
  await mkdir(path.join(root, 'skills', 'example'), { recursive: true });
  await writeFile(path.join(root, 'skills', 'example', 'SKILL.md'), '---\nname: example\ndescription: synthetic test fixture\n---\n');
  const roots = { skills: path.join(root, 'skills'), cache: path.join(root, 'cache') };
  const client = new Client({ name: 'protocol-test', version: '1.0.0' });
  const logs = path.join(root, 'logs');
  await mkdir(logs);
  await writeFile(path.join(logs, 'synthetic.jsonl'), JSON.stringify({ type: 'response_item', payload: { type: 'message', id: 'synthetic', role: 'user', content: [{ type: 'input_text', text: '$example' }] } }) + '\n');
  const usageOptions = { roots: [logs], stateFile: path.join(root, 'index', 'usage.json') };
  const archiveOptions = { roots, archiveRoot: path.join(root, 'archive') };
  const code = `import {createServer} from ${JSON.stringify(new URL('../src/server.mjs', import.meta.url).href)}; import {UsageIndex} from ${JSON.stringify(new URL('../src/usage-index.mjs', import.meta.url).href)}; import {SkillNotes} from ${JSON.stringify(new URL('../src/skill-notes.mjs', import.meta.url).href)}; import {ArchiveManager} from ${JSON.stringify(new URL('../src/archive.mjs', import.meta.url).href)}; import {StdioServerTransport} from '@modelcontextprotocol/sdk/server/stdio.js'; import {Adoptions} from ${JSON.stringify(new URL('../src/adoptions.mjs', import.meta.url).href)}; import {PluginCalls} from ${JSON.stringify(new URL('../src/plugin-calls.mjs', import.meta.url).href)}; let queries = 0; await createServer(${JSON.stringify(roots)}, {pluginCalls: new PluginCalls(${JSON.stringify(path.join(root, 'plugin-calls.json'))}), adoptions: new Adoptions(${JSON.stringify(path.join(root, 'adoptions.json'))}), skillNotes: new SkillNotes(${JSON.stringify(path.join(root, 'notes.json'))}), archiveManager: new ArchiveManager(${JSON.stringify(archiveOptions)}), usageIndex: new UsageIndex(${JSON.stringify(usageOptions)}), queryPlugins: async () => { if (queries++) throw new Error('synthetic failure'); return {plugins: [], checkedAt: '2026-01-01T00:00:00Z', evidence: 'synthetic'}; }}).connect(new StdioServerTransport());`;
  const transport = new StdioClientTransport({ command: process.execPath, args: ['--input-type=module', '-e', code], cwd: fileURLToPath(new URL('..', import.meta.url)), stderr: 'pipe' });
  try {
    await client.connect(transport);
    const { tools } = await client.listTools();
    assert.equal(tools.length, 11);
    assert.deepEqual(tools[0]._meta['openai/ui'].entrypoints, [{ type: 'global' }]);
    const uri = tools[0]._meta.ui.resourceUri;
    const { contents } = await client.readResource({ uri });
    const revision = createHash('sha256').update(contents[0].text).digest('hex').slice(0, 16);
    assert.equal(uri, `ui://codex-skill-manager/dashboard-${revision}.html`);
    await assert.rejects(client.readResource({ uri: 'ui://codex-skill-manager/dashboard.html' }));
    assert.equal(contents[0].mimeType, 'text/html;profile=mcp-app');
    assert.match(contents[0].text, /id="activity-panel"/);
    assert.doesNotMatch(contents[0].text, /id="(?:skills|search|archives|management-plan|usage)"/);
    assert.ok(!contents[0].text.includes('/* APP_BUNDLE */'));
    const result = await client.callTool({ name: 'open_skill_manager', arguments: {} });
    assert.equal(result.isError, undefined);
    assert.equal(result.structuredContent.mode, 'inventory');
    assert.equal(result.structuredContent.usage, null);
    assert.equal(result.structuredContent.skills.length, 1);
    assert.equal(result.structuredContent.skills[0].name, 'example');
    const callArgs={calls:[{id:'protocol-call-00001',plugin:'github',tool:'mcp__codex_apps__github_get_repo'}]};
    assert.equal((await client.callTool({name:'record_plugin_calls',arguments:callArgs})).isError,undefined);
    await client.callTool({name:'record_plugin_calls',arguments:callArgs});
    const callView=(await client.callTool({name:'query_usage',arguments:{timeZone:'Asia/Shanghai'}})).structuredContent;
    assert.equal(callView.pluginCalls.total,1);
    assert.equal(callView.adoptions.total,0);
    assert.equal(callView.pluginCalls.catalog[0].name,'github');
    const skill = result.structuredContent.skills[0];
    const recordArgs = {id:'protocol-batch-000001',skills:['example','example']};
    const recorded = await client.callTool({name:'record_skill_use',arguments:recordArgs});
    assert.deepEqual(recorded.content,[{type:'text',text:'OK'}]);
    assert.equal(recorded.structuredContent,undefined);
    await client.callTool({name:'record_skill_use',arguments:recordArgs});
    assert.equal((await client.callTool({name:'open_skill_manager',arguments:{}})).structuredContent.adoptions.total,2);
    const noteArgs = { id: skill.id, fingerprint: skill.fingerprint, note: 'synthetic retention reason', retain: true, expectedRevision: 0 };
    const noted = await client.callTool({ name: 'save_skill_note', arguments: noteArgs });
    assert.equal(noted.structuredContent.skills[0].annotation.note, noteArgs.note);
    assert.equal(noted.structuredContent.skills[0].annotation.contentChanged, false);
    assert.equal((await client.callTool({ name: 'save_skill_note', arguments: noteArgs })).isError, true);
    assert.equal((await client.callTool({ name: 'save_skill_note', arguments: { ...noteArgs, fingerprint: '0'.repeat(64), expectedRevision: 1 } })).isError, true);
    await appendFile(path.join(root, 'skills', 'example', 'SKILL.md'), '\nupdated synthetic content');
    assert.equal((await client.callTool({ name: 'open_skill_manager', arguments: {} })).structuredContent.skills[0].annotation.contentChanged, true);
    const checked = await client.callTool({ name: 'check_plugin_status', arguments: {} });
    assert.deepEqual(checked.structuredContent.pluginRegistry.plugins, []);
    const failed = await client.callTool({ name: 'check_plugin_status', arguments: {} });
    assert.equal(failed.isError, true);
    assert.equal(failed.structuredContent, undefined);
    const imported = await client.callTool({ name: 'import_usage', arguments: {} });
    assert.equal(imported.structuredContent.usage.counts['explicit-marker'].events, 1);
    const repeated = await client.callTool({ name: 'import_usage', arguments: {} });
    assert.equal(repeated.structuredContent.usage.counts['explicit-marker'].events, 1);
    assert.equal(repeated.structuredContent.usage.coverage.bytesRead, 0);
    assert.ok(repeated.structuredContent.pluginRegistry);
    await appendFile(path.join(logs, 'synthetic.jsonl'), JSON.stringify({ type: 'response_item', payload: { type: 'message', id: 'second', role: 'user', content: [{ type: 'input_text', text: '$example' }] } }) + '\n');
    const scanned = await client.callTool({ name: 'open_skill_manager', arguments: {} });
    assert.equal(scanned.structuredContent.usage.counts['explicit-marker'].events, 1);
    const continued = await client.callTool({ name: 'import_usage', arguments: {} });
    assert.equal(continued.structuredContent.usage.counts['explicit-marker'].events, 2);
    const period = await client.callTool({ name: 'query_usage', arguments: { from: '2026-01-01T00:00:00Z' } });
    assert.equal(period.structuredContent.usage.totalEvents, 0); // fixture timestamps are unknown
    const withinPeriod = await client.callTool({ name: 'import_usage', arguments: {} });
    assert.equal(withinPeriod.structuredContent.usage.totalEvents, 0);
    assert.equal(withinPeriod.structuredContent.usage.period.from, '2026-01-01T00:00:00.000Z');
    const allTime = await client.callTool({ name: 'query_usage', arguments: {} });
    assert.equal(allTime.structuredContent.usage.totalEvents, 2);
    const invalidPeriod = await client.callTool({ name: 'query_usage', arguments: { from: '2026-01-02T00:00:00Z', to: '2026-01-01T00:00:00Z' } });
    assert.equal(invalidPeriod.isError, true);
    assert.equal((await client.callTool({ name: 'open_skill_manager', arguments: {} })).structuredContent.usage.totalEvents, 2);
    const preview = await client.callTool({ name: 'preview_skill_archive', arguments: { skillId: result.structuredContent.skills[0].id } });
    assert.equal(preview.structuredContent.mode, 'management-plan');
    const cancelled = await client.callTool({ name: 'cancel_skill_plan', arguments: { token: preview.structuredContent.plan.token } });
    assert.equal(cancelled.structuredContent.mode, 'management-cancelled');
    const refused = await client.callTool({ name: 'execute_skill_plan', arguments: { token: preview.structuredContent.plan.token } });
    assert.equal(refused.isError, true);
    if (process.platform === 'win32') {
      const plan = await client.callTool({ name: 'preview_skill_archive', arguments: { skillId: result.structuredContent.skills[0].id } });
      const archive = await client.callTool({ name: 'execute_skill_plan', arguments: { token: plan.structuredContent.plan.token } });
      assert.equal(archive.structuredContent.operation.status, 'archived');
      assert.equal(archive.structuredContent.skills.length, 0);
      const retryAfterRemoval = await client.callTool({name:'record_skill_use',arguments:recordArgs});
      assert.deepEqual(retryAfterRemoval.content,[{type:'text',text:'OK'}]);
      assert.equal((await client.callTool({name:'open_skill_manager',arguments:{}})).structuredContent.adoptions.total,2);
      const restore = await client.callTool({ name: 'preview_skill_restore', arguments: { archiveId: archive.structuredContent.operation.id } });
      const restored = await client.callTool({ name: 'execute_skill_plan', arguments: { token: restore.structuredContent.plan.token } });
      assert.equal(restored.structuredContent.skills.length, 1);
    }
    await assert.rejects(client.readResource({ uri: 'file:///private.txt' }));
    const missing = await client.callTool({ name: 'delete_skill', arguments: {} });
    assert.equal(missing.isError, true);
    // A cold service restores the persisted index without importing new log records.
    await appendFile(path.join(logs, 'synthetic.jsonl'), JSON.stringify({type:'response_item',payload:{type:'message',id:'not-imported',role:'user',content:[{type:'input_text',text:'$example'}]}})+'\n');
    const restarted = new Client({name:'cold-open-test',version:'1.0.0'});
    try {
      await restarted.connect(new StdioClientTransport({command:process.execPath,args:['--input-type=module','-e',code],cwd:fileURLToPath(new URL('..',import.meta.url)),stderr:'pipe'}));
      const opened = await restarted.callTool({name:'open_skill_manager',arguments:{}});
      assert.equal(opened.structuredContent.usage.totalEvents,2);
      assert.ok(opened.structuredContent.usage.activity);
      assert.ok(opened.structuredContent.usage.activity.timeZone);
      assert.equal(opened.structuredContent.adoptions.total,2);
    } finally { await restarted.close(); }
  } finally { await client.close(); await rm(root, { recursive: true, force: true }); }
});
